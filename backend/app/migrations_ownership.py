"""Ownership roots; descendants inherit the immutable owner of their account."""

import sqlite3

SQLITE_ROOTS = {
    "accounts": """id INTEGER PRIMARY KEY AUTOINCREMENT, name TEXT NOT NULL,
        type TEXT NOT NULL DEFAULT 'checking', currency TEXT NOT NULL DEFAULT 'USD',
        opening_balance REAL NOT NULL DEFAULT 0, active INTEGER NOT NULL DEFAULT 1,
        created_at TEXT NOT NULL, opening_balance_cents INTEGER,
        user_id INTEGER NOT NULL DEFAULT 1 REFERENCES users(id) ON DELETE RESTRICT,
        UNIQUE(user_id,name)""",
    "budgets": """id INTEGER PRIMARY KEY AUTOINCREMENT, category TEXT,
        monthly_limit REAL, month_year TEXT, monthly_limit_cents INTEGER,
        user_id INTEGER NOT NULL DEFAULT 1 REFERENCES users(id) ON DELETE RESTRICT,
        UNIQUE(user_id,category)""",
}

USERS_SQL = """CREATE TABLE users (
    id INTEGER PRIMARY KEY,
    email TEXT,
    email_key TEXT UNIQUE,
    phone TEXT,
    email_verified_at TEXT,
    phone_verified_at TEXT,
    email_notifications INTEGER NOT NULL DEFAULT 0 CHECK(email_notifications IN (0,1)),
    sms_notifications INTEGER NOT NULL DEFAULT 0 CHECK(sms_notifications IN (0,1)),
    monthly_reports INTEGER NOT NULL DEFAULT 0 CHECK(monthly_reports IN (0,1)),
    active INTEGER NOT NULL DEFAULT 1 CHECK(active IN (0,1)),
    CHECK((email IS NULL) = (email_key IS NULL)),
    CHECK(email_verified_at IS NULL OR email IS NOT NULL),
    CHECK(phone_verified_at IS NULL OR phone IS NOT NULL)
)"""


def migrate_ownership(conn, _base_currency="USD"):
    sqlite = isinstance(conn, sqlite3.Connection)
    for table in ("transactions", "recurring_transactions"):
        # Identifiers come only from the fixed legacy table list.
        orphan_sql = (
            f"SELECT 1 FROM {table} t WHERE NOT EXISTS "
            "(SELECT 1 FROM accounts a WHERE a.id=t.account_id) LIMIT 1"
        )  # nosec B608
        if conn.execute(orphan_sql).fetchone():
            raise ValueError("Ownership migration requires owner review of orphan financial entries")
    conn.execute(
        USERS_SQL
        if sqlite
        else USERS_SQL.replace(
            "id INTEGER PRIMARY KEY", "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", 1
        )
    )
    conn.execute("INSERT INTO users(id) VALUES (1)")
    if not sqlite:
        conn.execute("SELECT setval(pg_get_serial_sequence('users','id'),1)")
    if sqlite:
        # Called with foreign keys disabled, inside the migration writer transaction.
        for table in SQLITE_ROOTS:
            objects = [
                row[0]
                for row in conn.execute(
                    "SELECT sql FROM sqlite_master WHERE tbl_name=? "
                    "AND type IN ('index','trigger') AND sql IS NOT NULL",
                    (table,),
                )
            ]
            columns = [row[1] for row in conn.execute(f"PRAGMA table_info({table})")]
            sequence = conn.execute("SELECT seq FROM sqlite_sequence WHERE name=?", (table,)).fetchone()
            conn.execute(f"CREATE TABLE {table}_owned({SQLITE_ROOTS[table]})")
            names = ",".join(columns)
            conn.execute(f"INSERT INTO {table}_owned({names}) SELECT {names} FROM {table}")  # nosec B608
            conn.execute(f"DROP TABLE {table}")
            conn.execute(f"ALTER TABLE {table}_owned RENAME TO {table}")
            if sequence:
                conn.execute("UPDATE sqlite_sequence SET seq=MAX(seq,?) WHERE name=?", (sequence[0], table))
            for statement in objects:
                conn.execute(statement)
    else:
        for table, column in (("accounts", "name"), ("budgets", "category")):
            conn.execute(
                f"ALTER TABLE {table} ADD COLUMN user_id INTEGER NOT NULL DEFAULT 1 "
                "REFERENCES users(id) ON DELETE RESTRICT"
            )
            conn.execute(f"ALTER TABLE {table} DROP CONSTRAINT {table}_{column}_key")
            conn.execute(f"ALTER TABLE {table} ADD UNIQUE(user_id,{column})")
    conn.execute("CREATE INDEX idx_accounts_owner ON accounts(user_id,id)")
    conn.execute("CREATE INDEX idx_users_active ON users(active,id)")
    if sqlite:
        _sqlite_guards(conn)
        if conn.execute("PRAGMA foreign_key_check").fetchone() is not None:
            raise ValueError("Ownership migration found broken financial references")
    else:
        conn.execute(POSTGRES_GUARDS)


# Prevent owner reassignment, null/orphan account references and cross-owner moves.
def _sqlite_guards(conn):
    for table in ("accounts", "budgets"):
        conn.execute(f"""CREATE TRIGGER ownership_{table}_update BEFORE UPDATE ON {table}
            WHEN NEW.user_id<>OLD.user_id
            BEGIN SELECT RAISE(ABORT,'Financial ownership is immutable'); END""")
    conn.execute("""CREATE TRIGGER ownership_accounts_delete BEFORE DELETE ON accounts
        BEGIN SELECT RAISE(ABORT,'Accounts must be deactivated'); END""")
    for table in ("transactions", "recurring_transactions"):
        for operation in ("INSERT", "UPDATE"):
            predicate = "NOT EXISTS(SELECT 1 FROM accounts WHERE id=NEW.account_id)"
            if operation == "UPDATE":
                predicate += (
                    " OR (SELECT user_id FROM accounts WHERE id=NEW.account_id) "
                    "<>(SELECT user_id FROM accounts WHERE id=OLD.account_id)"
                )
            conn.execute(f"""CREATE TRIGGER ownership_{table}_{operation.lower()}
                BEFORE {operation} ON {table} WHEN {predicate}
                BEGIN SELECT RAISE(ABORT,'Invalid financial ownership'); END""")
    for operation in ("INSERT", "UPDATE"):
        changed_owner = (
            " OR (SELECT user_id FROM accounts WHERE id=NEW.from_account_id) "
            "<>(SELECT user_id FROM accounts WHERE id=OLD.from_account_id)"
            if operation == "UPDATE"
            else ""
        )
        transfer_sql = f"""CREATE TRIGGER ownership_transfers_{operation.lower()}
            BEFORE {operation} ON transfers
            WHEN (SELECT user_id FROM accounts WHERE id=NEW.from_account_id)
               <>(SELECT user_id FROM accounts WHERE id=NEW.to_account_id) {changed_owner}
            BEGIN SELECT RAISE(ABORT,'Invalid financial ownership'); END"""  # nosec B608
        conn.execute(transfer_sql)


POSTGRES_GUARDS = """
CREATE FUNCTION finance_user_state_lock() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    PERFORM pg_advisory_xact_lock(618370201);
    RETURN NULL;
END $$;
CREATE TRIGGER ownership_user_state BEFORE UPDATE OF active ON users
    FOR EACH STATEMENT EXECUTE FUNCTION finance_user_state_lock();
CREATE FUNCTION finance_ownership_guard() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_TABLE_NAME IN ('accounts','budgets') THEN
        IF TG_OP='DELETE' THEN
            RAISE EXCEPTION USING ERRCODE='23514', MESSAGE='Accounts must be deactivated';
        END IF;
        IF NEW.user_id<>OLD.user_id THEN
            RAISE EXCEPTION USING ERRCODE='23514', MESSAGE='Financial ownership is immutable';
        END IF;
    ELSIF TG_TABLE_NAME='transfers' THEN
        IF (SELECT user_id FROM accounts WHERE id=NEW.from_account_id)
           IS DISTINCT FROM (SELECT user_id FROM accounts WHERE id=NEW.to_account_id)
           OR (TG_OP='UPDATE' AND
               (SELECT user_id FROM accounts WHERE id=NEW.from_account_id)
               IS DISTINCT FROM (SELECT user_id FROM accounts WHERE id=OLD.from_account_id)) THEN
            RAISE EXCEPTION USING ERRCODE='23514', MESSAGE='Invalid financial ownership';
        END IF;
    ELSE
        IF NOT EXISTS(SELECT 1 FROM accounts WHERE id=NEW.account_id)
           OR (TG_OP='UPDATE' AND
               (SELECT user_id FROM accounts WHERE id=NEW.account_id)
               IS DISTINCT FROM (SELECT user_id FROM accounts WHERE id=OLD.account_id)) THEN
            RAISE EXCEPTION USING ERRCODE='23514', MESSAGE='Invalid financial ownership';
        END IF;
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER ownership_accounts BEFORE UPDATE OR DELETE ON accounts
    FOR EACH ROW EXECUTE FUNCTION finance_ownership_guard();
CREATE TRIGGER ownership_budgets BEFORE UPDATE ON budgets
    FOR EACH ROW EXECUTE FUNCTION finance_ownership_guard();
CREATE TRIGGER ownership_transactions BEFORE INSERT OR UPDATE ON transactions
    FOR EACH ROW EXECUTE FUNCTION finance_ownership_guard();
CREATE TRIGGER ownership_recurring BEFORE INSERT OR UPDATE ON recurring_transactions
    FOR EACH ROW EXECUTE FUNCTION finance_ownership_guard();
CREATE TRIGGER ownership_transfers BEFORE INSERT OR UPDATE ON transfers
    FOR EACH ROW EXECUTE FUNCTION finance_ownership_guard();
"""
